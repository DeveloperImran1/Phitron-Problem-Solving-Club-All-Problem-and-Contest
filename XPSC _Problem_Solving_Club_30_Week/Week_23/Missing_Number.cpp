#include <bits/stdc++.h>
using namespace std;

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n;
    cin >> n;
    if (n == 9)
    {
        cout << 1;
    }
    else if (n == 8)
    {
        cout << 2;
    }
    else if (n == 7)
    {
        cout << 3;
    }
    else if (n == 6)
    {
        cout << 4;
    }

    return 0;
}